void shiftOutMultiple(uint8_t *data, uint8_t length){
	for(int i = length - 1; i >= 0; i--) {
        for(int bit = 7; bit >= 0; bit--) {
            HAL_GPIO_WritePin(GPIOB, GPIO_PIN_9, (data[i] >> bit) & 0x01 ? GPIO_PIN_SET : GPIO_PIN_RESET); 
            HAL_GPIO_WritePin(GPIOB, GPIO_PIN_0, GPIO_PIN_SET);   
            HAL_GPIO_WritePin(GPIOB, GPIO_PIN_0, GPIO_PIN_RESET); 
        }
    }
}
// B?ng mã LED 7 do?n (a,b,c,d,e,f,g) cho các s? 0-9
// 0x3F = hi?n th? s? 0, 0x06 = hi?n th? s? 1, v.v.
#define NUM_DIGITS 6
const uint8_t LED7S_MAP[10] = {
    0x3F, // 0 ? a,b,c,d,e,f
    0x06, // 1 ? b,c
    0x5B, // 2 ? a,b,d,e,g
    0x4F, // 3 ? a,b,c,d,g
    0x66, // 4 ? b,c,f,g
    0x6D, // 5 ? a,c,d,f,g
    0x7D, // 6 ? a,c,d,e,f,g
    0x07, // 7 ? a,b,c
    0x7F, // 8 ? a,b,c,d,e,f,g
    0x6F  // 9 ? a,b,c,d,f,g
};

void display(uint32_t number){
	uint8_t display_buffer[6] = {0, 0, 0, 0, 0, 0};
	for(int i = 0; i < 6; i++) {
        uint8_t digit = number % 10;
        display_buffer[i] = LED7S_MAP[digit];
        number /= 10;
    }
	
		shiftOutMultiple(display_buffer, N);
		
		HAL_GPIO_WritePin(GPIOB, GPIO_PIN_1, GPIO_PIN_SET);  
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_1, GPIO_PIN_RESET); 
}
